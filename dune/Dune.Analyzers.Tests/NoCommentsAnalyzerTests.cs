    [Fact]
    public async Task PolicyRoundTripKeepsStringsAndNewlines()
    {
        const string source = """
            namespace TemplateApp.Features.Tasks.Domain;
            public sealed class TaskRules
            {
                public string Check() => "kept";
            }
            // trailing
            """;

        var first = DuneCommentPolicy.RemoveComments(source);
        Assert.Contains("kept", first);
        Assert.Equal(first, DuneCommentPolicy.RemoveComments(first));
        Assert.Equal(
            source.Count(character => character == '\n'),
            first.Count(character => character == '\n'));
    }
