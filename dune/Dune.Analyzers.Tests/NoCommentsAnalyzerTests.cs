    [Fact]
    public async Task LineCommentInsideBackendIsRejected()
    {
        var diagnostics = await AnalyzerHost.AnalyzeAsync(
            new List<(string, string)>
            {
                ("backend/Features/Tasks/Domain/TaskRules.cs", """
                    namespace TemplateApp.Features.Tasks.Domain;
                    public sealed class TaskRules
                    {
                        public int Check() => 1;
                    }
                    // trailing note
                    """),
            },
            AnalyzerHost.Only<NoCommentsAnalyzer>());

        var violation = Assert.Single(diagnostics, diagnostic => diagnostic.Id == "DUNE0009");
        Assert.Equal(5, violation.Location.GetLineSpan().StartLinePosition.Line);
    }

